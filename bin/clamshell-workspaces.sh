#!/usr/bin/env bash
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib.sh"

module="$HOME/.config/default/hypr/monitor-workspaces.lua"
upstream="${OMARCHY_PATH:-/usr/share/omarchy}/default/hypr/monitor-workspaces.lua"
marker="-- Generated by JuMParchy from Omarchy's monitor-workspaces.lua."

if [[ -e $module || -L $module ]]; then
  if [[ -L $module || $(head -n 1 "$module") != "$marker" ]]; then
    fail "Clamshell workspaces: keeping your existing $module"
    exit 0
  fi
fi

if [[ ${1:-} == remove || ! -f $upstream ]]; then
  if [[ -f $module ]]; then
    rm "$module"
  fi
  exit 0
fi

mkdir -p "$(dirname "$module")"
candidate="$(mktemp "$module.XXXXXXXX")"
trap 'rm -f "$candidate"' EXIT
cat "$upstream" > "$candidate"
if ! patch --silent --batch --forward --fuzz=0 --no-backup-if-mismatch --reject-file=- \
  "$candidate" < "$SCRIPT_DIR/../patches/clamshell-workspaces.patch" >/dev/null; then
  fail "Clamshell workspaces: the patch does not match this version of Omarchy"
  if [[ -f $module ]]; then
    rm "$module"
  fi
  exit 0
fi

# Seed the laptop identity when first installing with the lid already closed.
laptop_file="${XDG_STATE_HOME:-$HOME/.local/state}/omarchy/monitor-workspaces-laptop"
if [[ ! -s $laptop_file ]]; then
  instance=()
  if [[ -z ${HYPRLAND_INSTANCE_SIGNATURE:-} ]]; then
    instance=(--instance 0)
  fi
  if identity=$(hyprctl "${instance[@]}" -j monitors all 2>/dev/null | jq -er '
    first(.[] | select(.name | test("^(eDP|LVDS|DSI)")) |
      if .description == "" then .name else .description end)
  ' 2>/dev/null); then
    mkdir -p "$(dirname "$laptop_file")"
    printf '%s\n' "$identity" > "$laptop_file"
  fi
fi

if { printf '%s\n' "$marker"; cat "$candidate"; } | cmp -s - "$module"; then
  exit 0
fi

sed -i "1i $marker" "$candidate"
mv -fT "$candidate" "$module"
ok "Installed the clamshell workspace override"
